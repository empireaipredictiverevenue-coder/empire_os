"""Read-only primary-source evidence for Predictive Revenue.

Runs EXISTING Permit Project Intelligence owner against original aggregate
acquisition signals, and optionally inspects an existing bounded official
UK tender-review JSON generated by its OWN source owner. No web/network
query, credential access, outreach, procurement bid, settlement or new agent.
"""
from __future__ import annotations

import argparse
from datetime import datetime,timezone
import json
from pathlib import Path

from empire_os.permit_project_intelligence import analyze_permit_project_intelligence
from empire_os.predictive_primary_source_economic_bridge import (
    build_primary_source_economic_review,
)


def main()->int:
    p=argparse.ArgumentParser()
    p.add_argument("--read-only",required=True,action="store_true")
    p.add_argument("--repo-root",default="/srv/empire_os")
    p.add_argument("--owner-uk-tender-review",default=None,
                   help="Already produced bounded UK Find a Tender owner JSON")
    args=p.parse_args()
    now=datetime.now(timezone.utc)
    permit=analyze_permit_project_intelligence(args.repo_root,now=now)
    tender=None
    if args.owner_uk_tender_review:
        file=Path(args.owner_uk_tender_review)
        if (file.is_symlink() or not file.is_file()
                or not 0<file.stat().st_size<=1_000_000):
            raise SystemExit("UK_TENDER_OWNER_FILE_UNAVAILABLE_OR_UNTRUSTED")
        with file.open("r",encoding="utf-8") as stream:
            tender=json.load(stream)
    output=build_primary_source_economic_review(permit,tender,as_of=now)
    print(json.dumps(output,sort_keys=True))
    return 0


if __name__=="__main__":
    raise SystemExit(main())
