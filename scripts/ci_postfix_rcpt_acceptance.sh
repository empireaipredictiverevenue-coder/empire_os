#!/usr/bin/env bash
# One-off GitHub-hosted runner acceptance. NO EmpireOS host effects.
# No third-party production dependency. Tests only localhost SMTP envelope.
set -euo pipefail

if [[ "${GITHUB_ACTIONS:-}" != "true" ||
      "${RUNNER_ENVIRONMENT:-}" != "github-hosted" ||
      "${GITHUB_REPOSITORY:-}" != "empireaipredictiverevenue-coder/empire_os" ||
      "${GITHUB_REF:-}" != "refs/heads/feature/postfix-isolated-rcpt-ci-20261014" ]]; then
  echo "HOLD_NOT_THE_AUTHORIZED_DISPOSABLE_CI_RUNNER"
  exit 2
fi

if [[ -e /usr/sbin/policy-rc.d ]]; then
  echo "HOLD_EXISTING_RUNNER_SERVICE_POLICY"
  exit 2
fi

if command -v postfix >/dev/null && postfix status >/dev/null 2>&1; then
  echo "HOLD_POSTFIX_ALREADY_RUNNING"
  exit 2
fi

TMP_DIR="$(mktemp -d -p /tmp empire-postfix-stage-ciXXXXXXXX)"
STARTED=0
POLICY_CREATED=0
cleanup() {
  if [[ "$STARTED" == "1" ]]; then sudo /usr/sbin/postfix stop >/dev/null 2>&1 || true; fi
  if [[ "$POLICY_CREATED" == "1" ]]; then sudo rm -f /usr/sbin/policy-rc.d; fi
  case "$TMP_DIR" in
    /tmp/empire-postfix-stage-ci*) sudo rm -rf -- "$TMP_DIR" ;;
  esac
}
trap cleanup EXIT

# A GitHub-hosted runner is disposable, but prevent Debian's package hooks
# from ever starting a default public SMTP listener during installation.
printf '#!/bin/sh\nexit 101\n' | sudo tee /usr/sbin/policy-rc.d >/dev/null
sudo chmod 0755 /usr/sbin/policy-rc.d
POLICY_CREATED=1
printf '%s\n' \
  'postfix postfix/main_mailer_type select Local only' \
  'postfix postfix/mailname string mx-stage.mail.empire-ai.co.uk' \
  | sudo debconf-set-selections
sudo apt-get update -qq
sudo env DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends postfix
echo "POSTFIX_VERSION=$(postconf mail_version | cut -d= -f2 | tr -d ' ')"
getent passwd postfix >/dev/null
getent group postdrop >/dev/null

# Config is generated by committed first-party source, NOT by untrusted mail.
export PYTHONPATH="$PWD"
python3 - "$TMP_DIR" <<'PY'
from pathlib import Path
import sys
from uuid import UUID
from empire_os.owned_postfix_staging_profile import (
    StageIdentity, generate_candidate_postfix_profile, validate_candidate_postfix_profile
)
root = Path(sys.argv[1])
ident = StageIdentity(str(UUID(int=121)), uid=15000, gid=15000)
files = generate_candidate_postfix_profile(ident, root=root)
verdict = validate_candidate_postfix_profile(files, identity=ident, root=root)
assert verdict["external_relay_enabled"] is False
assert verdict["wildcard_or_catchall_admitted"] is False
assert verdict["smtp_submission_enabled"] is False
for name, body in files.items():
    path = root / name
    assert not path.exists() and not path.is_symlink()
    path.write_text(body, encoding="utf-8")
    path.chmod(0o600)
print("STAGING_POLICY_GENERATED=TRUE")
PY

sudo install -o root -g root -m 0644 "$TMP_DIR/main.cf" /etc/postfix/main.cf
sudo install -o root -g root -m 0644 "$TMP_DIR/master.cf" /etc/postfix/master.cf
sudo /usr/sbin/postmap "hash:$TMP_DIR/recipients"
sudo chown root:postfix "$TMP_DIR" "$TMP_DIR/recipients.db"
sudo chmod 0750 "$TMP_DIR"
sudo chmod 0640 "$TMP_DIR/recipients.db"

EXACT="reply+00000000-0000-0000-0000-000000000079@mail.empire-ai.co.uk"
APPROVED="$(sudo /usr/sbin/postmap -q "$EXACT" "hash:$TMP_DIR/recipients")"
if [[ -z "$APPROVED" ]]; then echo "HOLD_FIXTURE_ALIAS_NOT_MAPPED"; exit 2; fi
for REJECT in \
  "reply@mail.empire-ai.co.uk" \
  "reply+00000000-0000-0000-0000-00000000007a@mail.empire-ai.co.uk" \
  "unknown@mail.empire-ai.co.uk" \
  "anyone@external.invalid"; do
  if [[ -n "$(sudo /usr/sbin/postmap -q "$REJECT" "hash:$TMP_DIR/recipients" || true)" ]]; then
    echo "HOLD_UNEXPECTED_RECIPIENT_MAP_MATCH"
    exit 2
  fi
done
echo "REAL_POSTMAP_LOOKUPS=PASS"

sudo /usr/sbin/postconf -n >/dev/null
sudo /usr/sbin/postconf -M >/dev/null
sudo /usr/sbin/postfix check

# Before starting, prove the test socket is unoccupied and has no public bind.
if ss -ltn | grep -Eq '(^|[^0-9])(:25|:2525|:465|:587)([^0-9]|$)'; then
  echo "HOLD_EXISTING_SMTP_LISTENER"
  exit 2
fi
sudo /usr/sbin/postfix start >/dev/null
STARTED=1

# Verify exactly one loopback SMTP TCP listener (no public SMTP).
python3 - <<'PY'
import socket,time
for _ in range(25):
    try:
        with socket.create_connection(("127.0.0.1",2525),timeout=1):
            print("REAL_LOOPBACK_POSTFIX_LISTENING=TRUE")
            break
    except OSError:
        time.sleep(.2)
else:
    raise SystemExit("HOLD_NO_REAL_POSTFIX_SMTP_LISTENER")
PY

python3 -m scripts.probe_postfix_staging_smtp_rcpt \
  --approved-isolated-loopback-rcpt-test
echo "REAL_POSTFIX_RCPT_ADMISSION=PASS"
echo "SMTP_DATA_SENT=FALSE"
echo "PUBLIC_PORT_PUBLISHED=FALSE"
echo "PRODUCTION_MX_CHANGED=FALSE"
