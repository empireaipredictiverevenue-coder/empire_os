from __future__ import annotations
import json
from pathlib import Path

import pytest

ROOT=Path("/srv/empire_os/runtime/nvidia_ontology_eval")
RECEIPT=ROOT/"nvidia_hosted_nlp_six_case_receipt_20261117_v2.json"
ORIGINAL=ROOT/"nvidia_hosted_nlp_six_case_receipt_20261117.json"

EXPECTED={
    "buyer_demand_edge_count":2,
    "capacity_edge_count":1,
    "unknown_demand_null":1,
    "known_demand_zero":1,
    "product_market_join":2,
    "positive_matching_capacity":1,
}


def test_real_synthetic_nlp_execution_six_cases():
    if not RECEIPT.is_file():
        pytest.skip("only available on EmpireOS after real authenticated release canary")
    assert RECEIPT.stat().st_mode & 0o077 == 0
    data=json.loads(RECEIPT.read_text())
    assert data["status"]=="VERIFIED"
    assert data["case_count"]==len(data["results"])==data["passed_count"]==6
    assert data["real_nvidia_nlp"] is True
    assert data["real_executed_sql_required"] is True
    assert data["paid_fallback"] is False
    assert data["customer_data_sent"] is False
    assert data["synthetic_only"] is True
    assert data["model"]=="openai/nvidia/nemotron-3.5-super-vl:free"
    assert {row["name"] for row in data["results"]}==set(EXPECTED)
    for row in data["results"]:
        assert row["http"]==200
        assert row["expected"]==row["actual"]==EXPECTED[row["name"]]
        assert row["sse_result_received"] is True
        assert row["has_executed_sql_response"] is True
        assert row["sql_source_and_filter_matches"] is True
        assert row["passed"] is True
        assert "sql" in row["events"] and "result" in row["events"]
        assert row["error_kind"] is None
        assert row["cancel_http"] is None
        assert row["duration_s"]>0
    assert ORIGINAL.is_file()
    previous=json.loads(ORIGINAL.read_text())
    assert previous["status"]=="NOT_VERIFIED" and previous["passed_count"]==0
    # Original trial must be preserved, not retroactively rewritten.


def test_result_count_is_not_conflated_with_generated_text():
    from scripts.accept_nvidia_free_nlp_six_20261117 import parse_count
    for value in ("2", "The answer is 2", None, {"answer":"two"}):
        assert parse_count(value) is None
    assert parse_count(['[{"buyer_demands_lane_count":2}]'])==2
    assert parse_count(['[{"known_zero_count":0}]'])==0
    assert parse_count('[{"count":2},{"count":1}]') is None
    assert parse_count('[{"count":2,"unrelated_number":3}]') is None
