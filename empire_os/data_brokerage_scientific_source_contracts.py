def register_scientific_source_contracts(registry: MutableMapping):
    """Extend one canonical registry. Conflicting source IDs fail closed."""
    if not isinstance(registry, MutableMapping):
        raise ValueError("existing_source_registry_not_mutable")
    candidate=scientific_source_contracts()
    for key,contract in candidate.items():
        if key in registry and registry[key]!=contract:
            raise ValueError("scientific_original_registry_id_conflict")
    registry.update(candidate)
    return {"registered_source_ids":tuple(sorted(candidate)),
            "source_contracts_count":len(candidate),
            "outbound_authorized":False,
            "customer_distribution_authorized":False}
