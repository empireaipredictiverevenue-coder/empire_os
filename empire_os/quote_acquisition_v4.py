"""V4 private acquisition evidence intelligence (owner-fed, non-executing).

Consumes explicitly identified evidence snapshots; no legacy SQLite, customer
contact disclosure, price promises, CRM changes, or invented settlement.
"""
from __future__ import annotations
from collections import Counter
from collections.abc import Mapping, Sequence
from decimal import Decimal, InvalidOperation
from typing import Any

from empire_os.quote_acquisition_v3 import review_quote_funnel

SCHEMA = "empire.quote_acquisition.v4"
CHANNELS = frozenset({"organic_search", "direct", "referral", "email_opt_in", "unknown"})
REJECTION_REASONS = frozenset({"out_of_area", "service_mismatch", "no_capacity",
                               "invalid_contact", "duplicate", "buyer_declined",
                               "unverified", "other"})


def _money(value: Any) -> Decimal | None:
    if isinstance(value, bool) or not isinstance(value, (str, int, Decimal)):
        return None
    try:
        amount = Decimal(str(value))
    except (ValueError, InvalidOperation):
        return None
    return amount if amount.is_finite() and 0 <= amount <= 1000000 else None


def analyze_acquisition_evidence(*, enquiries: Sequence[Mapping[str, Any]],
                                 buyer_candidates: Mapping[str, Sequence[Mapping[str, Any]]]
                                 ) -> dict[str, Any]:
    """Aggregate non-PII source/duplicate/rejection/cost insights on top of V3."""
    core = review_quote_funnel(enquiries=enquiries, buyer_candidates=buyer_candidates)
    fingerprints = set()
    channels = {}
    duplicate_count = 0
    reject_counts = Counter()
    for row in enquiries:
        ref = row["enquiry_ref"]
        attr = row.get("attribution", {})
        if not isinstance(attr, Mapping):
            raise ValueError("attribution mapping required")
        channel = attr.get("channel")
        channel = channel if channel in CHANNELS else "unknown"
        fingerprint = row.get("duplicate_token")
        # Only an opaque, privacy-preserving token generated by a trusted owner.
        # A bare email/phone must never be used as a duplicate identifier.
        if fingerprint is not None:
            if (not isinstance(fingerprint, str) or
                not fingerprint.startswith("dedupe:v1:") or
                len(fingerprint) < 20 or len(fingerprint) > 160 or
                "@" in fingerprint):
                raise ValueError("trusted opaque duplicate token required")
            if fingerprint in fingerprints:
                duplicate_count += 1
            fingerprints.add(fingerprint)
        reason = row.get("rejection_reason")
        if reason in REJECTION_REASONS:
            reject_counts[reason] += 1
        cost = _money(attr.get("verified_acquisition_cost")) if attr.get("cost_verified") is True else None
        # Cost attribution is only an owner assertion, not independent accounting.
        item = channels.setdefault(channel, {"enquiries": 0, "known_cost": Decimal(0), "cost_entries": 0})
        item["enquiries"] += 1
        if cost is not None:
            item["known_cost"] += cost
            item["cost_entries"] += 1
    # Do not compute ROI or profit until independent financial and outcome proof.
    return {
        "schema_version": SCHEMA,
        "mode": "OBSERVE",
        "funnel": core,
        "duplicate_token_collisions": duplicate_count,
        "duplicate_status": "POTENTIAL_DUPLICATES_FOR_OWNER_REVIEW",
        "channel_summary": {
            name: {"enquiries": data["enquiries"],
                   "owner_asserted_known_cost": str(data["known_cost"]),
                   "cost_records": data["cost_entries"],
                   "profit": None, "roi": None}
            for name, data in sorted(channels.items())
        },
        "rejections": dict(sorted(reject_counts.items())),
        "source_authority": "UNVERIFIED_OWNER_INPUT",
        "canonical_empiredb_connected": False,
        "outbound_authorized": False,
        "payment_execution": False,
        "crm_writes": False,
        "realised_revenue": None,
    }
